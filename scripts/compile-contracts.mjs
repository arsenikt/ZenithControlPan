import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'
import solc from 'solc'

const root = process.cwd()
const sourceDirectory = path.join(root, 'contracts')
const artifactsDirectory = path.join(root, 'artifacts', 'contracts')

async function sourceFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true })
  const nested = await Promise.all(entries.map(async (entry) => {
    const fullPath = path.join(directory, entry.name)
    if (entry.isDirectory()) return sourceFiles(fullPath)
    return entry.name.endsWith('.sol') ? [fullPath] : []
  }))
  return nested.flat()
}

const files = await sourceFiles(sourceDirectory)
const sources = Object.fromEntries(await Promise.all(files.map(async (file) => [
  path.relative(root, file).replaceAll('\\', '/'),
  { content: await readFile(file, 'utf8') },
])))
const catalog = JSON.parse(await readFile(path.join(sourceDirectory, 'catalog.json'), 'utf8'))
const output = JSON.parse(solc.compile(JSON.stringify({
  language: 'Solidity',
  sources,
  settings: {
    optimizer: { enabled: true, runs: 300 },
    evmVersion: 'cancun',
    outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object', 'evm.deployedBytecode.object'] } },
  },
})))

for (const message of output.errors ?? []) {
  if (message.severity === 'error') console.error(message.formattedMessage)
  else console.warn(message.formattedMessage)
}
if ((output.errors ?? []).some((item) => item.severity === 'error')) process.exit(1)

const compiled = new Map()
for (const [sourceName, contracts] of Object.entries(output.contracts ?? {})) {
  for (const [contractName, artifact] of Object.entries(contracts)) {
    compiled.set(contractName, { sourceName, ...artifact })
  }
}

const artifacts = {}
await rm(artifactsDirectory, { recursive: true, force: true })
await mkdir(artifactsDirectory, { recursive: true })
for (const definition of catalog) {
  const artifact = compiled.get(definition.contractName)
  if (!artifact) throw new Error(`Contract ${definition.contractName} not found`)
  artifacts[definition.key] = {
    ...definition,
    sourceName: artifact.sourceName,
    abi: artifact.abi,
    bytecode: `0x${artifact.evm.bytecode.object}`,
    deployedBytecode: `0x${artifact.evm.deployedBytecode.object}`,
  }
  await writeFile(path.join(artifactsDirectory, `${definition.key}.json`), `${JSON.stringify(artifacts[definition.key], null, 2)}\n`)
}

const moduleText = `// Generated by scripts/compile-contracts.mjs.\n` +
  `export const CONTRACT_CATALOG = Object.freeze(${JSON.stringify(catalog, null, 2)});\n\n` +
  `export const CONTRACT_ARTIFACTS = Object.freeze(${JSON.stringify(artifacts, null, 2)});\n` +
  `export const SOLC_VERSION = ${JSON.stringify(solc.version())};\n`
await writeFile(path.join(root, 'electron', 'contract-artifacts.mjs'), moduleText)
console.log(`Compiled ${catalog.length} suite contracts for Zenith Control Panel.`)
